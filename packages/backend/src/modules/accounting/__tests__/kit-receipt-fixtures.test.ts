import { describe, expect, it } from 'vitest'
import se25 from './fixtures/merchant-receipts/kit-merchant-se25.json' with { type: 'json' }
import reverseCharge from './fixtures/merchant-receipts/kit-merchant-reverse-charge.json' with { type: 'json' }
import { compareStatedTotal, receiptStatementFrom } from '../receipt-statement.js'
import { sellerFromMerchantReceipt } from '../receipt-underlag.js'

/**
 * #4913: the merchant kit's receipts, beside the demo merchant's. They are the
 * paywall proxy's own builder output (`packages/paywall-proxy/src/receipt.ts`,
 * over the shared `buildReceipt`), regenerated byte for byte by
 * `packages/paywall-proxy/src/receipt-fixtures.test.ts`. These tests read them
 * with the SAME reader Haven uses, so a kit receipt is accepted exactly as a
 * demo merchant's is.
 */

const SETTLED_ATOMIC = '10000' // the product's price: $0.01 in USDC base units

describe('the kit receipts are read by Haven’s accounting (#4913)', () => {
  it('accepts the SE_25 receipt: 25% VAT included in the price, and the stated total matches the settled amount', () => {
    const statement = receiptStatementFrom(se25)
    expect(statement).not.toBeNull()
    expect(statement!.currency).toBe('USDC')
    expect(statement!.merchantVatTreatment).toBe('SE_25')
    expect(statement!.totals).toEqual({ exclVat: '0.008', vatPercent: 25, vatAmount: '0.002', inclVat: '0.01' })
    expect(statement!.lines).toHaveLength(1)
    expect(statement!.lines[0]).toMatchObject({
      description: se25.rader[0].beskrivning,
      quantity: 1,
      unitPriceExclVat: '0.008',
      vatPercent: 25,
      vatAmount: '0.002',
      totalInclVat: '0.01',
    })
    expect(compareStatedTotal(statement!, { token: 'USDC', amountAtomic: SETTLED_ATOMIC, decimals: 6 })).toBe('matches')
  })

  it('accepts the reverse-charge receipt: a stated VAT of zero, both VAT numbers, and the stated total matches', () => {
    const statement = receiptStatementFrom(reverseCharge)
    expect(statement).not.toBeNull()
    expect(statement!.merchantVatTreatment).toBe('REVERSE_CHARGE')
    expect(statement!.totals).toEqual({ exclVat: '0.01', vatPercent: 0, vatAmount: '0', inclVat: '0.01' })
    expect(statement!.lines[0]).toMatchObject({ vatPercent: 0, vatAmount: '0', totalInclVat: '0.01' })
    expect(compareStatedTotal(statement!, { token: 'USDC', amountAtomic: SETTLED_ATOMIC, decimals: 6 })).toBe('matches')
    // The buyer block is never read into the statement, so the buyer's VAT
    // number stays out of it; the seller's is on the receipt's seller block.
    expect(JSON.stringify(statement)).not.toContain('DE123456789')
    expect(reverseCharge.kopare.deklaration.moms_nr).toBe('DE123456789')
    expect(reverseCharge.saljare.moms_nr).toBe('SE559123456701')
  })

  it('reads the seller correctly off both receipts', () => {
    for (const receipt of [se25, reverseCharge]) {
      expect(sellerFromMerchantReceipt(receipt)).toEqual({
        name: 'Kit Merchant AB',
        orgNo: '559123-4567',
        vatNo: 'SE559123456701',
      })
    }
  })

  it('names no Haven address or contact: the seller block is the merchant’s', () => {
    for (const receipt of [se25, reverseCharge]) {
      const text = JSON.stringify(receipt)
      expect(text).not.toContain('haven.xyz')
      expect(text).not.toContain('Haven Demo AB')
      expect(receipt.saljare.name).toBe('Kit Merchant AB')
    }
  })
})
