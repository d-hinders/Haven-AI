import { describe, expect, it } from 'vitest'
import se25 from './fixtures/merchant-receipts/demo-merchant-se25.json' with { type: 'json' }
import reverseCharge from './fixtures/merchant-receipts/demo-merchant-reverse-charge.json' with { type: 'json' }
import {
  RECEIPT_STATEMENT_MAX_LINES,
  RECEIPT_STATEMENT_MAX_TEXT,
  compareStatedTotal,
  receiptStatementFrom,
} from '../receipt-statement.js'
import { sellerFromMerchantReceipt } from '../receipt-underlag.js'

/**
 * #4875: the merchant's stated lines and VAT, read off its receipt. The two
 * fixtures are the demo merchant's own receipts, generated by its
 * `generateInvoice` (`packages/demo-merchant-mcp/src/invoice.ts`) — one
 * `SE_25`, one `REVERSE_CHARGE` — so these tests read the real shape.
 */

function clone<T>(value: T): T {
  return JSON.parse(JSON.stringify(value)) as T
}

describe('receiptStatementFrom (#4875)', () => {
  it('reads the lines, the totals, the treatment and the currency of an SE_25 receipt', () => {
    expect(receiptStatementFrom(se25)).toEqual({
      currency: 'USDC',
      merchantVatTreatment: 'SE_25',
      lines: [
        {
          description: se25.rader[0].beskrivning,
          quantity: 1,
          unitPriceExclVat: '0.0004',
          vatPercent: 25,
          vatAmount: '0.0001',
          totalInclVat: '0.0005',
        },
      ],
      totals: { exclVat: '0.0004', vatPercent: 25, vatAmount: '0.0001', inclVat: '0.0005' },
    })
  })

  it('a reverse-charge receipt states a VAT of zero — a stated zero, not "not stated"', () => {
    const statement = receiptStatementFrom(reverseCharge)
    expect(statement).not.toBeNull()
    expect(statement!.merchantVatTreatment).toBe('REVERSE_CHARGE')
    expect(statement!.totals).toEqual({ exclVat: '0.0005', vatPercent: 0, vatAmount: '0', inclVat: '0.0005' })
    expect(statement!.lines[0].vatPercent).toBe(0)
    expect(statement!.lines[0].vatAmount).toBe('0')
  })

  it('reads only its own keys: the buyer block (and the buyer VAT number) never reaches it', () => {
    const statement = receiptStatementFrom(reverseCharge)
    expect(JSON.stringify(statement)).not.toContain('DE123456789')
    expect(JSON.stringify(statement)).not.toContain('SE559412345601')
  })

  it('tolerates keys added later — a SEK block, an order id, more seller details, a new invoice-number format', () => {
    const extended = {
      ...clone(se25),
      fakturanummer: 'HAVEN-DEMO-2026-11-17-000123',
      payment_intent_id: 'pi_3Q',
      sek: { belopp_exkl_moms: '0.004', moms_belopp: '0.001', totalt_inkl_moms: '0.005', kurs: '10.42' },
      saljare: { ...se25.saljare, webbplats: 'https://demo.example' },
      rader: [{ ...se25.rader[0], artikelnummer: 'CN-50', sek_totalt: '0.005' }],
    }
    const statement = receiptStatementFrom(extended)
    expect(statement).toEqual(receiptStatementFrom(se25))
    // Merchant-stated SEK figures are not read.
    expect(JSON.stringify(statement)).not.toContain('10.42')
  })

  it('reads several lines in order', () => {
    const two = clone(se25)
    two.rader.push({ ...two.rader[0], beskrivning: 'Second line', antal: 3 })
    const statement = receiptStatementFrom(two)!
    expect(statement.lines.map((l) => [l.description, l.quantity])).toEqual([
      [se25.rader[0].beskrivning, 1],
      ['Second line', 3],
    ])
  })

  it('is "not stated" for no receipt, a non-object, and a receipt without lines', () => {
    expect(receiptStatementFrom(null)).toBeNull()
    expect(receiptStatementFrom(undefined)).toBeNull()
    expect(receiptStatementFrom('a string')).toBeNull()
    expect(receiptStatementFrom([se25])).toBeNull()
    const { rader: _rader, ...noLines } = clone(se25)
    expect(receiptStatementFrom(noLines)).toBeNull()
    expect(receiptStatementFrom({ ...clone(se25), rader: [] })).toBeNull()
  })

  it('a receipt with no momsbehandling still reads, with no merchant treatment', () => {
    const { momsbehandling: _m, ...noTreatment } = clone(se25)
    expect(receiptStatementFrom(noTreatment)?.merchantVatTreatment).toBeNull()
  })

  describe('a malformed receipt is "not stated" and never throws — no partial read', () => {
    const malformed: Array<[string, (r: Record<string, unknown> & { rader: Array<Record<string, unknown>> }) => void]> = [
      ['an amount given as a number', (r) => { r.totalt_inkl_moms = 0.0005 }],
      ['a negative total', (r) => { r.totalt_inkl_moms = '-0.0005' }],
      ['a negative line amount', (r) => { r.rader[0].moms_belopp = '-1' }],
      ['an amount with a sign or exponent', (r) => { r.belopp_exkl_moms = '5e-4' }],
      ['a VAT percent above 100', (r) => { r.moms_procent = 125 }],
      ['a negative VAT percent', (r) => { r.rader[0].moms_procent = -25 }],
      ['a VAT percent given as a string', (r) => { r.moms_procent = '25' }],
      ['a zero quantity', (r) => { r.rader[0].antal = 0 }],
      ['a quantity given as a string', (r) => { r.rader[0].antal = '1' }],
      ['an empty description', (r) => { r.rader[0].beskrivning = '   ' }],
      ['an oversized description', (r) => { r.rader[0].beskrivning = 'x'.repeat(RECEIPT_STATEMENT_MAX_TEXT + 1) }],
      ['a description with a control character', (r) => { r.rader[0].beskrivning = 'Line\u0000break' }],
      ['a line that is not an object', (r) => { r.rader.push('a line' as unknown as Record<string, unknown>) }],
      ['too many lines', (r) => { r.rader = Array.from({ length: RECEIPT_STATEMENT_MAX_LINES + 1 }, () => ({ ...r.rader[0] })) }],
      ['rader not an array', (r) => { (r as Record<string, unknown>).rader = { 0: r.rader[0] } }],
      ['no currency', (r) => { delete r.valuta }],
      ['a currency that is not a code', (r) => { r.valuta = 'US dollars!' }],
      ['a malformed treatment', (r) => { r.momsbehandling = 42 }],
    ]
    for (const [name, mutate] of malformed) {
      it(name, () => {
        const receipt = clone(se25) as unknown as Record<string, unknown> & { rader: Array<Record<string, unknown>> }
        mutate(receipt)
        expect(() => receiptStatementFrom(receipt)).not.toThrow()
        expect(receiptStatementFrom(receipt)).toBeNull()
      })
    }

    it('one bad line among good ones yields no lines at all', () => {
      const receipt = clone(se25)
      receipt.rader.push({ ...receipt.rader[0], totalt_inkl_moms: 'n/a' })
      expect(receiptStatementFrom(receipt)).toBeNull()
    })

    it('a hostile getter reads as not stated', () => {
      const hostile = Object.defineProperty(clone(se25), 'rader', {
        get() {
          throw new Error('boom')
        },
      })
      expect(() => receiptStatementFrom(hostile)).not.toThrow()
      expect(receiptStatementFrom(hostile)).toBeNull()
    })
  })

  it('leaves the seller-block read unchanged', () => {
    expect(sellerFromMerchantReceipt(se25)).toEqual({
      name: 'Haven Demo AB',
      orgNo: '559412-3456',
      vatNo: 'SE559412345601',
    })
  })
})

describe('compareStatedTotal (#4875)', () => {
  const statement = receiptStatementFrom(se25)!

  it('matches when the stated total in the settled token equals the settled amount, at any scale', () => {
    expect(compareStatedTotal(statement, 'USDC', '0.0005')).toBe('matches')
    expect(compareStatedTotal(statement, 'usdc', '0.000500')).toBe('matches')
  })

  it('differs when the receipt total and the settled amount disagree', () => {
    expect(compareStatedTotal(statement, 'USDC', '0.001')).toBe('differs')
  })

  it('is not comparable in another currency, or with no settled amount', () => {
    expect(compareStatedTotal({ ...statement, currency: 'SEK' }, 'USDC', '0.0005')).toBe('not_comparable')
    expect(compareStatedTotal(statement, 'USDC', null)).toBe('not_comparable')
    expect(compareStatedTotal(statement, null, '0.0005')).toBe('not_comparable')
    expect(compareStatedTotal(statement, 'USDC', 'not a number')).toBe('not_comparable')
  })
})
