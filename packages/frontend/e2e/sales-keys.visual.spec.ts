/**
 * Visual regression for the Sales keys on `/sales?tab=setup` (#4905, epic
 * #4885): the Setup tab with a live, a never-used and a revoked key, and the
 * create dialog showing the secret once.
 *
 * Scenarios x viewports (x the two schemes the projects run) =
 * `sales-keys-<scenario>-<viewport>[-dark].png` under
 * `e2e/__screenshots__/sales-keys.visual.spec.ts/`:
 *
 *   - `setup`   — the keys list inside the Setup card.
 *   - `created` — the dialog after Create, with the FAKE secret
 *                 (`SALES_KEY_FAKE_SECRET`, a sample no route accepts).
 *
 * The clock is frozen before `goto` so "Last used 2 minutes ago" is stable.
 * Baselines are generated by the *Update visual baselines* workflow, not from
 * a laptop.
 */
import { expect, test, type Page } from '@playwright/test'
import { VISUAL_SKIP_REASON, VISUAL_SPECS_ENABLED } from './support/visual-mode'
import {
  dismissMobileSidebar,
  mockHavenApi,
  SALES_FROZEN_NOW,
  SALES_KEY_FAKE_SECRET,
  seedAuthenticatedSession,
  serveSales,
  serveSalesKeys,
} from './fixtures/haven-api'
// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore — plain .mjs; the SINGLE source of evidence viewports.
import { VIEWPORTS as SHARED_VIEWPORTS } from '../scripts/evidence-viewports.mjs'
// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore — plain .mjs; the #1738 un-clip and the #1936 non-blank proof.
import { assertCaptureNotBlank, unclipScrollShell } from '../scripts/full-page-capture.mjs'
import { THEME_STORAGE_KEY } from '../src/lib/theme-bootstrap'

const VIEWPORTS = SHARED_VIEWPORTS as ReadonlyArray<{ name: string; width: number; height: number }>

const FULL_PAGE_MAX_DIFF_PIXELS = 150
const PIXEL_THRESHOLD = 0.02
const ANCHOR_TIMEOUT_MS = 60_000

interface Scenario {
  name: 'setup' | 'created'
  assert: (page: Page) => Promise<void>
}

const SCENARIOS: Scenario[] = [
  {
    name: 'setup',
    async assert(page) {
      const list = page.getByTestId('sales-keys-list')
      await expect(list).toContainText('sk_merchant_4f2a…')
      await expect(list).toContainText('Never used')
      await expect(list.getByText('Revoked', { exact: true })).toHaveCount(1)
      await expect(list.getByRole('button', { name: 'Revoke' })).toHaveCount(2)
    },
  },
  {
    name: 'created',
    async assert(page) {
      await page.getByRole('button', { name: 'Create Sales key' }).first().click()
      await page.getByRole('dialog', { name: 'Create Sales key' }).getByRole('button', { name: 'Create Sales key' }).click()
      const dialog = page.getByRole('dialog', { name: 'Your new Sales key' })
      await expect(dialog).toContainText(SALES_KEY_FAKE_SECRET)
    },
  },
]

test.describe('sales keys visual regression (#4905)', () => {
  test.skip(!VISUAL_SPECS_ENABLED, VISUAL_SKIP_REASON)

  const schemeOf = (testInfo: { project: { name: string } }): 'light' | 'dark' =>
    testInfo.project.name === 'chromium-desktop-dark' ? 'dark' : 'light'

  test.beforeEach(async ({ page }, testInfo) => {
    await mockHavenApi(page)
    await seedAuthenticatedSession(page)
    if (schemeOf(testInfo) === 'dark') {
      await page.addInitScript((themeKey: string) => {
        window.localStorage.setItem(themeKey, 'dark')
      }, THEME_STORAGE_KEY)
    }
  })

  for (const scenario of SCENARIOS) {
    for (const vp of VIEWPORTS) {
      test(`${scenario.name} renders pixel-stable (${vp.name})`, async ({ page }, testInfo) => {
        const schemeSuffix = schemeOf(testInfo) === 'dark' ? '-dark' : ''
        const label = `sales keys ${scenario.name} · ${vp.name}`

        await page.clock.setFixedTime(SALES_FROZEN_NOW)
        await serveSales(page, 'overview')
        await serveSalesKeys(page)

        await page.setViewportSize({ width: vp.width, height: vp.height })
        await page.goto('/sales?tab=setup')

        await expect(page.getByTestId('sales-keys-section')).toHaveCount(1, { timeout: ANCHOR_TIMEOUT_MS })
        await dismissMobileSidebar(page)
        await scenario.assert(page)

        await page.evaluate(() => document.fonts.ready)
        await page.waitForLoadState('networkidle')
        await expect(page.locator('.animate-pulse'), `${label}: skeleton on screen`).toHaveCount(0)

        await unclipScrollShell(page)
        const devicePixelRatio = await page.evaluate(() => window.devicePixelRatio)
        await assertCaptureNotBlank(await page.screenshot({ fullPage: true }), {
          label,
          viewportDevicePx: vp.height * devicePixelRatio,
        })
        await expect(page).toHaveScreenshot(`sales-keys-${scenario.name}-${vp.name}${schemeSuffix}.png`, {
          fullPage: true,
          animations: 'disabled',
          caret: 'hide',
          maxDiffPixels: FULL_PAGE_MAX_DIFF_PIXELS,
          threshold: PIXEL_THRESHOLD,
        })
      })
    }
  }
})
