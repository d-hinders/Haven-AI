/**
 * Visual regression for `/sales` (#4900, epic #4885): the Overview with a
 * period of payments, the first run before any sale, and the Products tab.
 *
 * The approved mockup (#4894, 2026-11-16) is the intent; #4908's review notes
 * said the consuming screens carry the baselines ("the new /design-system
 * section has no pixel baseline. Baseline the consuming screens here").
 *
 * ── The capture matrix ───────────────────────────────────────────────────────
 *
 * Eight scenarios × two viewports (× the two schemes the projects run) =
 * `sales-<scenario>-<viewport>[-dark].png` under
 * `e2e/__screenshots__/sales.visual.spec.ts/`:
 *
 *   - `overview` — tiles, the not-counted notice, the by-day chart, By product,
 *     By payer and the day-grouped ledger, from one fixture whose figures agree
 *     (`salesSummary` and `salesPayments`, `fixtures/haven-api.ts`).
 *   - `overview-sek` — the same fixture for a SEK user (#4963): converted at
 *     today's rate, "≈" on the two totals.
 *   - `overview-stripe` — the same period plus two sales received at a
 *     registered Stripe deposit address (#4954, #4981): four tiles counting
 *     them, the Revenue foot and the list line splitting "in Haven" from "in
 *     Stripe", the two-series chart and the mark on the two Stripe rows
 *     (`salesSummaryWithStripe`).
 *   - `overview-subcent` (#5105) — a period whose revenue sums are not whole
 *     USDC cents, for a SEK user with no rate served, so the page is in USDC
 *     mode: the Revenue tile reads `12,345.6789 USDC`, the widest realistic
 *     figure the #5088 sum rule prints, and it must stay on ONE line (the
 *     #4400 rule: a money figure never wraps) at both widths. In USDC mode the
 *     unit sits in the tile's unit slot and the figure is set compact (owner
 *     decision 2026-11-26 on #5105).
 *   - `payment-stripe` — one of those sales opened: the mark beside the
 *     status, "to your Stripe address", and the Stripe notice (#4954).
 *   - `first-run` — the account has never been paid: the seller definition,
 *     "No sales yet" and the three setup steps, none done.
 *   - `first-run-progressed` (#4985) — the same screen with progress: a Sales
 *     key exists and the product list address reads `ok`, so all three steps
 *     are done, the count reads "3 of 3 done" and the card says the seller is
 *     connected. Still unpaid, so the first-run screen is still what shows.
 *   - `products` — the catalogue read OK: the table with exact USDC prices, the
 *     network, sales in the period and the freshness line.
 *
 * Whole-page, as `analytics.visual.spec.ts` is: what is at risk is the
 * composition of the page, not one card.
 *
 * ── Determinism ──────────────────────────────────────────────────────────────
 *
 * The page's period is the last 30 UTC days from `Date.now()`, and the chart
 * draws one slot per day, so the clock is frozen BEFORE `goto` to
 * `SALES_FROZEN_NOW`; the freshness line's "4m ago" is `timeAgo` and moves with
 * it too. Every date in the fixtures is absolute. Fonts settled, network idle,
 * no skeleton on screen: the waits every whole-page capture in this suite makes.
 *
 * ── The structural half (#2827) ──────────────────────────────────────────────
 *
 * Every `toHaveCount` below runs under `VISUAL_STRUCTURE_ONLY=1` on any
 * platform, where pixels are not compared. Both breakdown tables and the
 * products table render twice (a `hidden lg:block` table and a `lg:hidden` row
 * list), so each assertion is scoped to the owning `data-testid` and to the
 * layout that is visible at that viewport, never a bare `.first()`.
 *
 * ── Baselines ────────────────────────────────────────────────────────────────
 *
 * Linux-rendered, like every baseline in this directory. They are generated by
 * the *Update visual baselines* workflow (`update-visual-baselines.yml`), not
 * from a laptop.
 */
import { expect, test, type Page } from '@playwright/test'
import { VISUAL_SKIP_REASON, VISUAL_SPECS_ENABLED } from './support/visual-mode'
import { expectFigureOnOneLine } from './support/money-figure'
import {
  dismissMobileSidebar,
  mockHavenApi,
  SALES_FROZEN_NOW,
  seedAuthenticatedSession,
  serveSales,
  serveSekUser,
  type SalesScenario,
} from './fixtures/haven-api'
// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore — plain .mjs; the SINGLE source of evidence viewports.
import { VIEWPORTS as SHARED_VIEWPORTS } from '../scripts/evidence-viewports.mjs'
// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore — plain .mjs; the #1738 un-clip and the #1936 non-blank proof.
import { assertCaptureNotBlank, unclipScrollShell } from '../scripts/full-page-capture.mjs'
import { THEME_STORAGE_KEY } from '../src/lib/theme-bootstrap'

const VIEWPORTS = SHARED_VIEWPORTS as ReadonlyArray<{ name: string; width: number; height: number }>

const FULL_PAGE_MAX_DIFF_PIXELS = 150
const PIXEL_THRESHOLD = 0.02
const ANCHOR_TIMEOUT_MS = 60_000

interface Scenario {
  name: 'overview' | 'overview-sek' | 'overview-stripe' | 'overview-subcent' | 'payment-stripe' | 'first-run' | 'first-run-progressed' | 'products'
  serve: SalesScenario
  /** Serve the SEK user (the converted Overview, #4963). */
  sek?: boolean
  path: string
  assert: (page: Page, vp: { name: string }) => Promise<void>
}

const desktop = (vp: { name: string }) => vp.name === 'desktop'

const SCENARIOS: Scenario[] = [
  {
    name: 'overview',
    serve: 'overview',
    path: '/sales',
    async assert(page, vp) {
      await expect(page.getByTestId('sales-tiles')).toHaveCount(1)
      await expect(page.getByTestId('sales-by-day')).toHaveCount(1)
      await expect(page.getByTestId('sales-ledger')).toHaveCount(1)
      // The not-counted notice names the move once.
      await expect(page.getByText('Not counted:')).toHaveCount(1)
      // By product renders twice (table from `lg`, rows below); one is visible.
      const byProduct = page.getByTestId('sales-by-product')
      await expect(byProduct).toHaveCount(1)
      await expect(byProduct.getByText('Chat completion').filter({ visible: true })).toHaveCount(1)
      await expect(page.getByTestId('sales-ledger').getByText('No product recorded')).toHaveCount(1)
      void vp
    },
  },
  {
    // #4963: the same fixture as `overview` for a SEK user — every figure is
    // converted at the fixture's SEK rate, the two totals carry "≈", rows and
    // breakdown lines do not.
    name: 'overview-sek',
    serve: 'overview',
    sek: true,
    path: '/sales',
    async assert(page) {
      await expect(page.getByTestId('sales-tiles')).toHaveCount(1)
      await expect(page.getByTestId('sales-ledger')).toHaveCount(1)
      await expect(page.getByTestId('stat-tile-revenue')).toContainText('\u2248')
      await expect(page.getByTestId('stat-tile-revenue')).not.toContainText('USDC')
      await expect(page.getByTestId('sales-ledger')).not.toContainText('\u2248')
    },
  },
  {
    // #4981: a Stripe-held sale is a sale. Four tiles in one row, no tile of
    // its own, Revenue the total with the split in its foot, and the list
    // line saying the same; the Stripe rows keep their mark.
    name: 'overview-stripe',
    serve: 'overview-stripe',
    path: '/sales',
    async assert(page) {
      await expect(page.getByTestId('sales-stripe-tile')).toHaveCount(0)
      await expect(page.getByTestId('sales-tiles').getByTestId(/^stat-tile-/)).toHaveCount(4)
      await expect(page.getByTestId('stat-tile-revenue')).toContainText('$2.17')
      await expect(page.getByTestId('stat-tile-revenue')).toContainText('$2.14 in Haven \u00b7 $0.03 in Stripe')
      await expect(page.getByTestId('stat-tile-sales')).toContainText('6')
      await expect(page.getByTestId('sales-payments-summary')).toContainText('Revenue $2.17 ($2.14 in Haven \u00b7 $0.03 in Stripe)')
      await expect(page.getByTestId('sales-ledger').getByText('Received in Stripe')).toHaveCount(2)
    },
  },
  {
    // #5105: the #5088 sum rule's widest realistic figure. A SEK user, but no
    // rate on any read, so the page is in USDC mode — no conversion, no "≈".
    // The Revenue figure must render on one line at both widths (#4400).
    name: 'overview-subcent',
    serve: 'overview-subcent',
    sek: true,
    path: '/sales',
    async assert(page) {
      const revenue = page.getByTestId('stat-tile-revenue')
      // #5105 owner decision: in USDC mode the unit sits in the tile's unit
      // slot and a 4+ integer-digit figure is set one size down (compact).
      await expect(revenue.locator('p').nth(1)).toHaveText(/^12,345\.6789\s*USDC$/)
      await expect(revenue.locator('p').nth(1)).toHaveClass(/text-xl/)
      await expect(revenue).not.toContainText('\u2248')
      await expect(revenue).not.toContainText('kr')
      await expectFigureOnOneLine(revenue, 'Sales Revenue')
      await expect(page.getByTestId('sales-by-product')).toContainText('8,230.4526 USDC')
    },
  },
  {
    name: 'payment-stripe',
    serve: 'overview-stripe',
    path: '/sales',
    async assert(page) {
      await page.getByTestId('sales-ledger').getByText('Joke').first().click()
      const panel = page.getByRole('dialog', { name: 'Joke' })
      await expect(panel).toHaveCount(1)
      await expect(panel.getByTestId('sales-payment-header').getByText('Received in Stripe')).toHaveCount(1)
      await expect(panel.getByTestId('sales-payment-header')).toContainText('to your Stripe address')
      await expect(panel).toContainText('It counts in your revenue, but not in any Haven balance')
    },
  },
  {
    name: 'first-run',
    serve: 'first-run',
    path: '/sales',
    async assert(page) {
      await expect(page.getByTestId('sales-first-run')).toHaveCount(1)
      await expect(page.getByText('No sales yet')).toHaveCount(1)
      await expect(page.getByTestId('sales-tiles')).toHaveCount(0)
      // #4985: the seller is introduced first, and no step is done without an
      // observation.
      await expect(page.getByTestId('seller-definition')).toHaveCount(1)
      await expect(page.getByTestId('sales-first-run-count')).toHaveText('0 of 3 done')
    },
  },
  {
    // #4985: the first-run screen with progress — a key and a product list
    // address reading `ok`, still unpaid.
    name: 'first-run-progressed',
    serve: 'first-run-progressed',
    path: '/sales',
    async assert(page) {
      await expect(page.getByTestId('sales-first-run')).toHaveCount(1)
      await expect(page.getByTestId('sales-first-run-count')).toHaveText('3 of 3 done')
      await expect(page.getByText('Your seller is connected. Sales appear here when someone pays.')).toHaveCount(1)
      await expect(page.getByTestId('sales-tiles')).toHaveCount(0)
    },
  },
  {
    name: 'products',
    serve: 'products-ok',
    path: '/sales?tab=products',
    async assert(page, vp) {
      const table = page.getByTestId('sales-products-table')
      await expect(table).toHaveCount(1)
      await expect(page.getByTestId('sales-products-freshness')).toContainText('Read from inference.example.com · 4m ago')
      // The exact price, a token surface: $0.018 is not rounded to a cent here.
      await expect(table.getByText('0.018 USDC').filter({ visible: true })).toHaveCount(1)
      await expect(table.getByText('No longer offered').filter({ visible: true })).toHaveCount(1)
      void desktop(vp)
    },
  },
]

async function expectNoSkeletons(page: Page, label: string) {
  await expect(
    page.locator('.animate-pulse'),
    `${label}: still rendering skeleton placeholders — the capture would bake in a mid-load frame`,
  ).toHaveCount(0)
}

test.describe('sales visual regression (#4900)', () => {
  test.skip(!VISUAL_SPECS_ENABLED, VISUAL_SKIP_REASON)

  const schemeOf = (testInfo: { project: { name: string } }): 'light' | 'dark' =>
    testInfo.project.name === 'chromium-desktop-dark' ? 'dark' : 'light'

  test.beforeEach(async ({ page }, testInfo) => {
    await mockHavenApi(page)
    await seedAuthenticatedSession(page)
    if (schemeOf(testInfo) === 'dark') {
      await page.addInitScript((themeKey: string) => {
        window.localStorage.setItem(themeKey, 'dark')
      }, THEME_STORAGE_KEY)
    }
  })

  for (const scenario of SCENARIOS) {
    for (const vp of VIEWPORTS) {
      test(`${scenario.name} renders pixel-stable (${vp.name})`, async ({ page }, testInfo) => {
        const scheme = schemeOf(testInfo)
        const schemeSuffix = scheme === 'dark' ? '-dark' : ''
        const label = `${scenario.name} · ${vp.name} · ${scheme}`

        // BEFORE `goto`: the page reads `Date.now()` for its period on first render.
        await page.clock.setFixedTime(SALES_FROZEN_NOW)
        await serveSales(page, scenario.serve)
        if (scenario.sek) await serveSekUser(page)

        await page.setViewportSize({ width: vp.width, height: vp.height })
        await page.goto(scenario.path)

        await expect(page.getByTestId('sales-page')).toHaveCount(1, { timeout: ANCHOR_TIMEOUT_MS })
        await expect(page.getByRole('heading', { name: 'Sales', exact: true, level: 1 })).toBeVisible({
          timeout: ANCHOR_TIMEOUT_MS,
        })
        await dismissMobileSidebar(page)

        await scenario.assert(page, vp)

        await page.evaluate(() => document.fonts.ready)
        await page.waitForLoadState('networkidle')
        await expectNoSkeletons(page, label)

        await unclipScrollShell(page)
        const devicePixelRatio = await page.evaluate(() => window.devicePixelRatio)
        await assertCaptureNotBlank(await page.screenshot({ fullPage: true }), {
          label,
          viewportDevicePx: vp.height * devicePixelRatio,
        })

        await expect(page).toHaveScreenshot(`sales-${scenario.name}-${vp.name}${schemeSuffix}.png`, {
          fullPage: true,
          animations: 'disabled',
          caret: 'hide',
          maxDiffPixels: FULL_PAGE_MAX_DIFF_PIXELS,
          threshold: PIXEL_THRESHOLD,
        })
      })
    }
  }
})
